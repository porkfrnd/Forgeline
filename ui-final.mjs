import { chromium } from "@playwright/test";
const BASE = process.argv[2];
const browser = await chromium.launch();
const errs = [];
for (const vp of [{ w: 1440, h: 900, tag: "desktop" }, { w: 800, h: 900, tag: "narrow" }]) {
  const page = await browser.newPage({ viewport: { width: vp.w, height: vp.h } });
  page.on("console", (m) => { if (m.type() === "error") errs.push(`${vp.tag}: ${m.text()}`); });
  page.on("pageerror", (e) => errs.push(`${vp.tag}: pageerror ${e.message}`));
  const minted = await (await fetch(`${BASE}/api/__test__/bootstrap`)).json();
  await page.goto(`${BASE}/?t=${minted.token}`);
  const cookie = (await page.context().cookies()).find((c) => c.name === "session")?.value;
  await page.evaluate(async ([base, c]) => {
    await fetch(`${base}/api/__test__/roots`, { method: "POST", headers: { "content-type": "application/json", Cookie: `session=${c}` }, body: JSON.stringify({ paths: ["/tmp/fl-fin"] }) });
    await fetch(`${base}/api/__test__/register-repo`, { method: "POST", headers: { "content-type": "application/json", Cookie: `session=${c}` }, body: JSON.stringify({ path: "/tmp/fl-fin/demo" }) });
  }, [BASE, cookie]);
  await page.goto(BASE);
  await page.waitForSelector(".work", { timeout: 15000 });
  await page.waitForTimeout(2000);
  await page.screenshot({ path: `screenshots/final-${vp.tag}-dashboard.png` });
  await page.locator(".rail-row").first().click();
  await page.waitForTimeout(2500);
  await page.screenshot({ path: `screenshots/final-${vp.tag}-changes.png` });
  await page.locator(".toolbar-history").click();
  await page.waitForTimeout(2500);
  await page.screenshot({ path: `screenshots/final-${vp.tag}-history.png`, fullPage: true });
  await page.locator(".toolbar-history").click();
  await page.locator(".toolbar-stash").click();
  await page.waitForTimeout(2000);
  await page.screenshot({ path: `screenshots/final-${vp.tag}-stash.png`, fullPage: true });
  await page.locator(".toolbar-stash").click();
  await page.locator(".brand-branch").click();
  await page.waitForTimeout(2000);
  await page.screenshot({ path: `screenshots/final-${vp.tag}-branches.png`, fullPage: true });
  await page.locator(".brand-branch").click();
  await page.locator(".toolbar-doctor").click();
  await page.waitForTimeout(2500);
  await page.screenshot({ path: `screenshots/final-${vp.tag}-doctor.png`, fullPage: true });
  await page.locator(".toolbar-doctor").click();
  await page.locator(".toolbar-release").click();
  await page.waitForTimeout(2000);
  await page.screenshot({ path: `screenshots/final-${vp.tag}-release.png`, fullPage: true });
  await page.locator(".toolbar-release").click();
  await page.locator("body").click({ position: { x: 5, y: 5 } });
  await page.close();
}
console.log("console errors:", errs.length === 0 ? "none" : JSON.stringify(errs, null, 1));
await browser.close();
